"""Ports only. Application code supplies all concrete implementations."""
from typing import Any, Protocol

from .config import MechanismSpec
from .decisions import Command, DecisionBundle
from .events import Event
from .observations import Message, Observation, ObservationFact
from .receipts import ExecutionReceipt
from .state import BatchExecutionResult, ExecutionResult, Feedback, TickContext, WorldSnapshot


class Policy(Protocol):
    policy_id: str
    version: str

    async def decide(self, observation: Observation) -> DecisionBundle: ...


class ObservationBuilder(Protocol):
    def observe(self, actor_id: str, snapshot: WorldSnapshot, candidates: list[ObservationFact]) -> Observation: ...


class ActionCompiler(Protocol):
    def compile(self, bundle: DecisionBundle, arrival_key: int) -> list[Command]: ...
    def compile_messages(self, bundle: DecisionBundle, tick: int) -> list[Message]: ...


class ObservationCommitEffect(Protocol):
    """Optional observer capability; returns a declared patch inside PreparedTick."""
    effect_spec: MechanismSpec

    def prepare_commit(self, snapshot: WorldSnapshot, observations: tuple[Observation, ...]) -> dict[str, Any]: ...


class Scenario(Protocol):
    scenario_id: str
    version: str
    owned_fields: frozenset[str]

    def initialize(self) -> dict[str, Any]: ...
    def boundary(self, context: TickContext) -> dict[str, Any]: ...
    def apply_event(self, context: TickContext, event: Event) -> dict[str, Any]: ...
    async def prepare_observations(self, context: TickContext) -> dict[str, Any]: ...
    def project_observation(self, context: TickContext, actor_id: str) -> list[ObservationFact]: ...
    def execute(self, context: TickContext, command: Command) -> ExecutionResult: ...
    def execute_batch(self, context: TickContext, commands: list[Command]) -> BatchExecutionResult: ...
    def feedback(self, context: TickContext, receipts: list[ExecutionReceipt]) -> Feedback: ...
    def validate(self, context: TickContext) -> None: ...
    def metrics(self, context: TickContext) -> dict[str, Any]: ...


class Mechanism(Protocol):
    spec: MechanismSpec

    def propose(self, context: TickContext) -> dict[str, Any]: ...


class TransactionParticipant(Protocol):
    participant_id: str
    state_schema_version: int

    def export_state(self) -> dict[str, Any]: ...
    def import_state(self, state: dict[str, Any]) -> None: ...
    def validate_state(self) -> None: ...


class CommitStore(Protocol):
    def commit(self, base: WorldSnapshot, prepared) -> Any: ...
    def is_committed(self, prepared) -> bool: ...
    def update_index(self) -> None: ...
